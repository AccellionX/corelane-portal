import { jsPDF } from "jspdf";
import { formatCurrency, formatDate } from "./format";
import type { Invoice, User } from "./types";
import { PLANS } from "./mock-data";

export function downloadInvoicePdf(invoice: Invoice, customer: User) {
  const plan = PLANS.find((p) => p.id === invoice.planId);
  const doc = new jsPDF();

  doc.setFontSize(20);
  doc.setTextColor(79, 70, 229);
  doc.text("Corelane", 20, 24);

  doc.setTextColor(24, 24, 27);
  doc.setFontSize(14);
  doc.text("Invoice", 20, 38);

  doc.setFontSize(10);
  doc.setTextColor(82, 82, 91);
  doc.text(`Number: ${invoice.number}`, 20, 50);
  doc.text(`Status: ${invoice.status}`, 20, 57);
  doc.text(`Issued: ${formatDate(invoice.issuedDate)}`, 20, 64);
  doc.text(`Due: ${formatDate(invoice.dueDate)}`, 20, 71);

  doc.setTextColor(24, 24, 27);
  doc.text("Bill to", 20, 88);
  doc.setTextColor(82, 82, 91);
  doc.text(customer.name, 20, 95);
  doc.text(customer.email, 20, 102);
  doc.text(customer.company, 20, 109);

  doc.setDrawColor(228, 228, 231);
  doc.line(20, 120, 190, 120);

  doc.setTextColor(24, 24, 27);
  doc.text("Description", 20, 130);
  doc.text("Amount", 160, 130);
  doc.setTextColor(82, 82, 91);
  doc.text(`${plan?.name ?? invoice.planId} subscription`, 20, 140);
  doc.text(formatCurrency(invoice.amount), 160, 140);

  doc.setFontSize(12);
  doc.setTextColor(24, 24, 27);
  doc.text(`Total due: ${formatCurrency(invoice.amount)}`, 20, 160);

  doc.setFontSize(8);
  doc.setTextColor(161, 161, 170);
  doc.text("Generated by Corelane demo · AccellionX", 20, 280);

  doc.save(`${invoice.number}.pdf`);
}
